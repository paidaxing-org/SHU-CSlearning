import java.util.*;

public class HelloJava  {
    public static void main(String[] args) {
        System.out.println("Hello,Java!");
        System.out.println("-----------");
        String s="Hello,Java!";
        System.out.println(s);
        //经过自己的测试，发现这两种形式都可以，第一种是直接输出一个字符串，第二个是先将Hello,Java赋给一个字符串s，再输出s
    }
}